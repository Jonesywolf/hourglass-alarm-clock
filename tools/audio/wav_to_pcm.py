#!/usr/bin/env python3
"""Convert a mono 16-bit WAV into the firmware's embedded alarm clip (C++ source).

    python tools/audio/wav_to_pcm.py [wav] [-o src/services/sound_alarm_clip.cpp] [--rate 16000]

The output is generated; do not edit it by hand. The rate must match HG_AUDIO_SAMPLE_RATE.
Standard library only.
"""
import argparse
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_WAV = ROOT / "assets" / "audio" / "alarm_clip_16k_mono.wav"
DEFAULT_OUT = ROOT / "src" / "services" / "sound_alarm_clip.cpp"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("wav", nargs="?", type=Path, default=DEFAULT_WAV)
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--rate", type=int, default=16000)
    args = parser.parse_args()

    with wave.open(str(args.wav), "rb") as clip:
        channels, width, rate, frames = (clip.getnchannels(), clip.getsampwidth(),
                                         clip.getframerate(), clip.getnframes())
        data = clip.readframes(frames)
    if channels != 1 or width != 2 or rate != args.rate:
        raise SystemExit(f"{args.wav.name}: need mono 16-bit {args.rate} Hz, "
                         f"got {channels} ch, {width * 8}-bit, {rate} Hz")
    if frames == 0:
        raise SystemExit(f"{args.wav.name}: empty clip")
    samples = [int.from_bytes(data[i:i + 2], "little", signed=True) for i in range(0, len(data), 2)]

    lines = [
        f"/* Generated by tools/audio/wav_to_pcm.py from assets/audio/{args.wav.name}. Do not edit.",
        " * Source and license: assets/audio/ATTRIBUTION.md (CC0). */",
        "",
        '#include "hg/config.h"',
        '#include "sound_internal.h"',
        "",
        f"static_assert(HG_AUDIO_SAMPLE_RATE == {args.rate}U, "
        '"Regenerate the clip with tools/audio/wav_to_pcm.py for the new sample rate");',
        "",
        f"const uint32_t hg_alarm_clip_frames = {frames};",
        "",
        "const int16_t hg_alarm_clip_pcm[] = {",
    ]
    for i in range(0, len(samples), 16):
        lines.append("    " + ", ".join(str(s) for s in samples[i:i + 16]) + ",")
    lines += ["};", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{args.output.name}: {frames} frames ({frames / rate:.2f} s, {frames * 2} bytes)")


if __name__ == "__main__":
    main()
