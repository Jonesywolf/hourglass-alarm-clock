#!/usr/bin/env python3
"""Convert the three approved mono 16-bit 16 kHz alarm WAVs to flash PCM."""

import argparse
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLIPS = [
    ("warm_mallets.wav", "hg_alarm_clip"),
    ("wooden_call.wav", "hg_alarm_wooden"),
    ("plucked_dawn.wav", "hg_alarm_plucked"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path,
                        default=ROOT / "src" / "services" / "sound_alarm_clip.cpp")
    args = parser.parse_args()
    lines = [
        "/* Generated by tools/audio/wav_to_pcm.py. Do not edit.",
        " * Original synthesis: assets/audio/ATTRIBUTION.md. */",
        "",
        '#include "hg/config.h"',
        '#include "sound_internal.h"',
        "",
        'static_assert(HG_AUDIO_SAMPLE_RATE == 16000U, "Regenerate alarm assets for the new rate");',
        "",
    ]
    for filename, symbol in CLIPS:
        path = ROOT / "assets" / "audio" / filename
        with wave.open(str(path), "rb") as clip:
            if (clip.getnchannels(), clip.getsampwidth(), clip.getframerate(),
                    clip.getnframes()) != (1, 2, 16000, 96000):
                raise SystemExit(f"{filename}: expected six-second mono 16-bit 16000 Hz WAV")
            data = clip.readframes(clip.getnframes())
        if len(data) != 192000:
            raise SystemExit(f"{filename}: truncated PCM")
        samples = [int.from_bytes(data[i:i + 2], "little", signed=True)
                   for i in range(0, len(data), 2)]
        lines += [f"const uint32_t {symbol}_frames = {len(samples)};",
                  f"const int16_t {symbol}_pcm[] = {{"]
        for i in range(0, len(samples), 16):
            lines.append("    " + ", ".join(str(s) for s in samples[i:i + 16]) + ",")
        lines += ["};", ""]
        print(f"{filename}: {len(samples)} frames, {len(data)} PCM bytes")
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
